import sys
from pathlib import Path

import pandas as pd

from state_codes import STATE_NAMES

ROOT = Path(__file__).resolve().parent.parent
MERGED = ROOT / "data" / "processed" / "merged_state_year.csv"
INTERIM = ROOT / "data" / "interim"
UNMATCHED = ROOT / "results" / "quality" / "unmatched_rows.csv"
OUT = ROOT / "results" / "quality" / "post_integration.md"

KEY = ["state", "year"]
EXPECTED_STATES, FIRST_YEAR, LAST_YEAR = 50, 2010, 2024
EXPECTED_ROWS = EXPECTED_STATES * (LAST_YEAR - FIRST_YEAR + 1)
BOUNDS = {
    "price_cents_kwh": (3, 60),
    "real_median_income": (20_000, 200_000),
    "share_electric_heat": (0, 1),
}


class Report:
    def __init__(self):
        self.lines, self.failures = [], []

    def h(self, text):
        self.lines += ["", f"## {text}", ""]

    def p(self, text):
        self.lines.append(text)

    def check(self, label, ok, detail=""):
        self.lines.append(f"- {'PASS' if ok else 'FAIL'}: {label}" + (f" ({detail})" if detail else ""))
        if not ok:
            self.failures.append(label)

    def table(self, df):
        self.lines += ["", _md_table(df), ""]


def _md_table(df):
    cols = list(df.columns)
    rows = ["| " + " | ".join(map(str, cols)) + " |", "| " + " | ".join("---" for _ in cols) + " |"]
    rows += ["| " + " | ".join(map(str, r)) + " |" for r in df.itertuples(index=False)]
    return "\n".join(rows)


def main():
    for path in (MERGED, UNMATCHED):
        if not path.exists():
            sys.exit(f"ERROR: missing input {path.relative_to(ROOT)} (run scripts/integrate.py first)")
    m = pd.read_csv(MERGED)
    unmatched = pd.read_csv(UNMATCHED)
    interim = {n: pd.read_csv(INTERIM / f"{n}_clean.csv") for n in ("eia", "fred", "acs", "cpi")}

    r = Report()
    r.p("# Post-integration data quality assessment")
    r.p("")
    r.p("Generated by `scripts/profile_integrated.py` from "
        f"`data/processed/merged_state_year.csv` ({len(m)} rows, {m.shape[1]} columns).")

    r.h("Completeness")
    r.check(f"row count equals {EXPECTED_STATES} states x {LAST_YEAR - FIRST_YEAR + 1} years = {EXPECTED_ROWS}",
            len(m) == EXPECTED_ROWS, f"found {len(m)}")
    r.check("all 50 states present", set(m["state"]) == set(STATE_NAMES.values()),
            f"missing: {sorted(set(STATE_NAMES.values()) - set(m['state']))}")
    r.check(f"every state has all years {FIRST_YEAR}-{LAST_YEAR}",
            (m.groupby("state")["year"].nunique() == LAST_YEAR - FIRST_YEAR + 1).all())
    core = ["price_cents_kwh", "real_price_cents_kwh", "real_median_income",
            "total_units", "units_electric_heat", "share_electric_heat"]
    nulls = m[core].isna().sum()
    r.check("no missing values in analysis columns", nulls.sum() == 0,
            ", ".join(f"{c}: {n}" for c, n in nulls.items() if n) or "0 missing")
    moe_nulls = int(m["share_electric_heat_moe"].isna().sum())
    r.p(f"- INFO: share_electric_heat_moe missing for {moe_nulls} rows (MOE not published for those estimates).")
    r.p("")
    r.p("Source rows not carried into the merged table (`results/quality/unmatched_rows.csv`):")
    if unmatched.empty:
        r.p("")
        r.p("_None._")
    else:
        r.table(unmatched.groupby(["source", "reason"]).size().reset_index(name="rows"))
    in_window = unmatched[~unmatched["reason"].str.startswith("year outside")]
    r.check("no in-window source rows lost to unmatched keys", in_window.empty,
            f"{len(in_window)} rows" if not in_window.empty else "")

    r.h("Accuracy")
    r.check("(state, year) key is unique", not m.duplicated(subset=KEY).any())
    for col, (lo, hi) in BOUNDS.items():
        out = m[(m[col] < lo) | (m[col] > hi)]
        r.check(f"{col} within plausible range [{lo}, {hi}]", out.empty,
                f"{len(out)} out of range" if not out.empty else f"observed {m[col].min()}-{m[col].max()}")
    r.check("units_electric_heat <= total_units", (m["units_electric_heat"] <= m["total_units"]).all())
    recomputed = m["units_electric_heat"] / m["total_units"]
    r.check("share_electric_heat equals units_electric_heat / total_units",
            (recomputed - m["share_electric_heat"]).abs().max() < 1e-6)

    for name, cols in {"eia": ["price_cents_kwh"], "fred": ["real_median_income"],
                       "acs": ["total_units", "units_electric_heat", "share_electric_heat"]}.items():
        src = interim[name][KEY + cols]
        joined = m[KEY + cols].merge(src, on=KEY, suffixes=("", "_src"))
        diffs = sum(int((joined[c] - joined[f"{c}_src"]).abs().gt(1e-9).sum()) for c in cols)
        r.check(f"{name.upper()} values identical to cleaned source after join", diffs == 0 and len(joined) == len(m),
                f"{diffs} differing values")

    cpi = interim["cpi"].set_index("year")["cpi_index"]
    base = int(m["dollar_base_year"].iloc[0])
    expected_real = (m["price_cents_kwh"] * cpi[base] / m["year"].map(cpi)).round(2)
    r.check(f"real_price_cents_kwh reproduces from price index (base year {base})",
            (expected_real - m["real_price_cents_kwh"]).abs().max() <= 0.011)

    r.p("")
    r.p("Year-over-year changes more than 3 standard deviations from the mean change "
        "(flagged for review, not removed):")
    flagged = []
    for col in ("price_cents_kwh", "real_median_income", "share_electric_heat"):
        d = m.sort_values(KEY).groupby("state")[col].diff()
        z = (d - d.mean()) / d.std()
        hits = m.loc[z.abs() > 3, KEY].assign(variable=col, change=d[z.abs() > 3].round(4))
        flagged.append(hits)
    flagged = pd.concat(flagged)
    r.table(flagged) if not flagged.empty else r.p("\n_None._")

    r.h("Consistency")
    r.check("state_abbr maps one-to-one to state", m.groupby("state")["state_abbr"].nunique().eq(1).all()
            and all(STATE_NAMES[a] == s for s, a in zip(m["state"], m["state_abbr"])))
    r.check("single dollar base year across all rows", m["dollar_base_year"].nunique() == 1)
    types = {t: [int(y) for y in sorted(g)] for t, g in m.groupby("estimate_type")["year"].unique().items()}
    non_acs1 = {t: y for t, y in types.items() if t != "acs1"}
    r.p(f"- INFO: ACS estimate type by year: {types}.")
    if non_acs1:
        r.p(f"- NOTE: years {sorted(sum(non_acs1.values(), []))} use a different ACS product "
            f"({', '.join(non_acs1)}); the 2020 1-year file was not released. These rows are kept and "
            "flagged via `estimate_type` so analyses can exclude them as a sensitivity check.")
    r.p("- NOTE: income comes from the CPS ASEC (via FRED) while housing counts come from the ACS; the two "
        "surveys use different samples, so the measures are linked by state and year but not by respondent.")

    r.h("Timeliness")
    coverage = pd.DataFrame([
        {"source": n.upper(), "first_year": int(df["year"].min()), "last_year": int(df["year"].max()),
         "years_used": f"{FIRST_YEAR}-{LAST_YEAR}" if n != "cpi" else f"{FIRST_YEAR}-{LAST_YEAR} + base year"}
        for n, df in interim.items()
    ])
    r.table(coverage)
    r.p(f"The integrated table ends in {int(m['year'].max())}, the latest year available from all three "
        "sources (ACS 1-year data trails the other sources by about one year). Later EIA and FRED years are "
        "listed in `unmatched_rows.csv` as outside the study window.")

    r.h("Summary")
    if r.failures:
        r.p(f"**{len(r.failures)} check(s) failed:** " + "; ".join(r.failures))
    else:
        r.p("**All checks passed.** Every in-window state-year from each source found a match, keys are unique, "
            "values are unchanged by the join, and derived fields reproduce from their inputs, which is "
            "evidence that the integration is reasonably successful.")

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(r.lines) + "\n")
    print(f"profile_integrated: wrote {OUT.relative_to(ROOT)}; {len(r.failures)} failed check(s)")
    if r.failures:
        for f in r.failures:
            print(f"  FAIL: {f}")
        sys.exit(1)


if __name__ == "__main__":
    main()
